"""Generates the collector's per-device Telegraf config:

  python -m fleet.collector_config > collector/telegraf.d/devices.conf

Built from inventory.toml (which devices, unit ids, sites) and
register_map.toml (where each value lives and how it's encoded), so the
collector can't drift from either. A unit test fails if the committed file is
out of date.

Metric names follow Prometheus conventions: base units in the name, so kW
registers become *_watts and percentages become *_ratio.
"""
from __future__ import annotations

import sys

from .inventory import Asset, load_inventory
from .registers import Register, load_map

GATEWAY = "tcp://modbus-gateway:502"
MEASUREMENT = "fleet"

# Register map unit -> (suffix of the metric name, factor to the base unit)
UNITS = {
    "": ("", 1),
    "s": ("seconds", 1),
    "Hz": ("hertz", 1),
    "V": ("volts", 1),
    "kW": ("watts", 1000),
    "kWp": ("watts", 1000),
    "kvar": ("var", 1000),
    "kWh": ("watt_hours", 1000),
    "%": ("ratio", 0.01),
    "m/s": ("meters_per_second", 1),
    "rpm": ("rpm", 1),
    "W/m2": ("watts_per_square_meter", 1),
    "C": ("celsius", 1),
}

# Registers read only to keep requests contiguous. The device type is already
# a label from the inventory.
OMITTED = {"device_type"}

HEADER = """\
# GENERATED by `python -m fleet.collector_config` from inventory.toml and
# fleet/register_map.toml. Don't edit by hand: change those and run
# scripts/generate-collector-config.sh. A unit test fails if this file is stale.
#
# One Modbus input per device, all through the read-only gateway. Separate
# inputs keep a dead device from holding up the others, and give each device
# its own gather statistics, which is how monitoring tells "no data" apart
# from "zero output".
"""


def field_name(reg: Register) -> str:
    if reg.unit not in UNITS:
        raise ValueError(f"{reg.name}: no Prometheus naming for unit {reg.unit!r}, add it to UNITS")
    suffix, _ = UNITS[reg.unit]
    return f"{reg.name}_{suffix}" if suffix else reg.name


def field_scale(reg: Register) -> float:
    _, factor = UNITS[reg.unit]
    return float(f"{reg.scale * factor:.12g}")  # 0.1 * 0.01 is 0.001, not 0.0010000000000000002


def render_field(reg: Register) -> str:
    parts = [f"address = {reg.address}", f'name = "{field_name(reg)}"', f'type = "{reg.type}"']
    if reg.name in OMITTED:
        parts.append("omit = true")
    elif field_scale(reg) != 1.0:
        parts.append(f"scale = {field_scale(reg)!r}")
    return "      { " + ", ".join(parts) + " },"


def render_device(asset: Asset) -> list[str]:
    registers = load_map(asset.type).registers.values()
    lines = [
        "[[inputs.modbus]]",
        f'  alias = "{asset.id}"',
        f'  name = "{asset.id}"',
        f'  controller = "{GATEWAY}"',
        '  configuration_type = "request"',
        "  exclude_register_type_tag = true",
        '  timeout = "2s"',
        '  tagexclude = ["name", "slave_id"]',
    ]
    for table in ("input", "holding"):
        fields = sorted((r for r in registers if r.register == table), key=lambda r: r.address)
        if not fields:
            continue
        lines += [
            "",
            "  [[inputs.modbus.request]]",
            f"    slave_id = {asset.unit}",
            f'    register = "{table}"',
            '    byte_order = "ABCD"',
            f'    measurement = "{MEASUREMENT}"',
            "    fields = [",
            *(render_field(r) for r in fields),
            "    ]",
            "    [inputs.modbus.request.tags]",
            f'      device = "{asset.id}"',
            f'      device_type = "{asset.type}"',
            f'      site = "{asset.site}"',
        ]
    return lines


def render(assets: list[Asset]) -> str:
    lines = HEADER.splitlines()
    for asset in assets:
        lines += ["", *render_device(asset)]
    lines += [
        "",
        "# Telegraf's own per-input statistics carry the alias. Label them like the",
        "# readings: look up the site in the inventory, then rename alias to device.",
        "[[processors.enum]]",
        "  order = 1",
        '  namepass = ["internal_gather"]',
        "  [[processors.enum.mapping]]",
        '    tags = ["alias"]',
        '    dest = "site"',
        "    [processors.enum.mapping.value_mappings]",
        *(f'      "{asset.id}" = "{asset.site}"' for asset in assets),
        "",
        "[[processors.rename]]",
        "  order = 2",
        '  namepass = ["internal_gather"]',
        "  [[processors.rename.replace]]",
        '    tag = "alias"',
        '    dest = "device"',
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render(load_inventory(sys.argv[1] if len(sys.argv) > 1 else "inventory.toml")))